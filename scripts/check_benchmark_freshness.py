#!/usr/bin/env python3
"""Verify that benchmark evidence was produced from current benchmark code.

Benchmark artifacts are intentionally portable JSON files.  This gate makes the
portable metadata actionable: an artifact must record the source commit that
produced it, that commit must be reachable from the checked-out revision, and
no benchmark-affecting source file may have changed between those revisions.

The command accepts one or more ``--artifact`` paths.  With no paths it emits a
passing, empty report; CI/release jobs should pass the freshly generated
artifact explicitly (usually under ``target/``) instead of silently trusting a
committed historical report. A dirty benchmark-affecting worktree fails closed
because the artifact's commit cannot describe uncommitted source changes.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

# Changes to documentation, plots, or generated output do not invalidate an
# artifact.  Changes to these paths can alter model behavior, split semantics,
# feature construction, or benchmark comparability and therefore invalidate it.
BENCHMARK_AFFECTING_PREFIXES = (
    "benchmarks/",
    "scripts/",
    "crates/cartoboost-core/",
    "crates/cartoboost-py/",
    "python/cartoboost/",
)
BENCHMARK_AFFECTING_FILES = {
    "Cargo.toml",
    "Cargo.lock",
    "pyproject.toml",
    "uv.lock",
}
COMMIT_RE = re.compile(r"^[0-9a-f]{7,40}$", re.IGNORECASE)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--artifact",
        action="append",
        default=[],
        type=Path,
        help="JSON benchmark artifact to verify (repeatable).",
    )
    parser.add_argument(
        "--current-commit",
        help="Override the checked-out commit (useful for deterministic CI/tests).",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="Repository root (defaults to the CartoBoost checkout).",
    )
    args = parser.parse_args(argv)
    report = check_benchmark_freshness(
        args.artifact,
        root=args.root,
        current_commit=args.current_commit,
    )
    print(json.dumps(report, indent=2, sort_keys=True))
    if not report["passed"]:
        raise SystemExit("benchmark freshness checks failed")
    return 0


def check_benchmark_freshness(
    artifacts: Iterable[Path | str] = (),
    *,
    root: Path = ROOT,
    current_commit: str | None = None,
    allow_dirty: bool = False,
) -> dict[str, Any]:
    """Return a machine-readable freshness report for *artifacts*.

    ``artifacts`` is explicit by design.  An empty set is a valid no-op report,
    allowing callers to keep the gate available for local workflows while CI
    supplies the output generated by its benchmark job.
    """

    root = Path(root).resolve()
    paths = [Path(path) for path in artifacts]
    if current_commit is None:
        current_commit, commit_error = _git_current_commit(root)
    else:
        commit_error = None

    rows: list[dict[str, Any]] = []
    for path in paths:
        resolved = path if path.is_absolute() else root / path
        rows.append(
            _check_artifact(
                resolved,
                root=root,
                current_commit=current_commit,
                commit_error=commit_error,
                allow_dirty=allow_dirty,
            )
        )

    return {
        "artifact_type": "cartoboost.benchmark_freshness_audit",
        "artifact_version": 1,
        "root": str(root),
        "current_commit": current_commit,
        "artifacts_requested": len(paths),
        "artifacts_checked": len(rows),
        "passed": all(row["passed"] for row in rows),
        "checks": rows,
    }


def _check_artifact(
    path: Path,
    *,
    root: Path,
    current_commit: str | None,
    commit_error: str | None,
    allow_dirty: bool,
) -> dict[str, Any]:
    row: dict[str, Any] = {
        "artifact": _display_path(path, root),
        "passed": False,
        "recorded_commit": None,
        "current_commit": current_commit,
        "commit_is_ancestor": False,
        "changed_benchmark_files": [],
        "dirty_benchmark_files": [],
        "reason": None,
    }
    if not path.exists():
        row["reason"] = "artifact does not exist"
        return row
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        row["reason"] = f"could not parse artifact: {exc}"
        return row

    recorded = _find_commit(payload)
    row["recorded_commit"] = recorded
    if not recorded or not COMMIT_RE.fullmatch(recorded):
        row["reason"] = "artifact does not record a valid git_commit"
        return row
    if commit_error or not current_commit or not COMMIT_RE.fullmatch(current_commit):
        row["reason"] = commit_error or "current checkout does not expose a valid git commit"
        return row

    ancestor, error = _is_ancestor(root, recorded, current_commit)
    row["commit_is_ancestor"] = ancestor
    if error:
        row["reason"] = error
        return row
    if not ancestor:
        row["reason"] = "recorded benchmark commit is not an ancestor of current commit"
        return row

    changed = _changed_benchmark_files(root, recorded, current_commit)
    row["changed_benchmark_files"] = changed
    if changed:
        row["reason"] = "benchmark-affecting source changed after artifact commit"
        return row
    if not allow_dirty:
        dirty = _dirty_benchmark_files(root)
        row["dirty_benchmark_files"] = dirty
        if dirty:
            row["reason"] = "benchmark-affecting source is dirty after artifact commit"
            return row

    row["passed"] = True
    row["reason"] = "artifact commit is current and benchmark source is unchanged"
    return row


def _find_commit(payload: Any) -> str | None:
    """Find the top-level benchmark provenance commit in a JSON payload."""

    if isinstance(payload, dict):
        for key in ("git_commit", "source_git_commit", "code_sha"):
            value = payload.get(key)
            if isinstance(value, str) and value.strip():
                return value.strip()
        for value in payload.values():
            found = _find_commit(value)
            if found:
                return found
    elif isinstance(payload, list):
        for value in payload:
            found = _find_commit(value)
            if found:
                return found
    return None


def _git_current_commit(root: Path) -> tuple[str | None, str | None]:
    try:
        completed = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        return None, f"could not resolve current git commit: {exc}"
    commit = completed.stdout.strip()
    return (commit or None), (None if commit else "git rev-parse returned an empty commit")


def _is_ancestor(root: Path, recorded: str, current: str) -> tuple[bool, str | None]:
    try:
        completed = subprocess.run(
            ["git", "merge-base", "--is-ancestor", recorded, current],
            cwd=root,
            capture_output=True,
            text=True,
        )
    except OSError as exc:
        return False, f"could not compare benchmark commit ancestry: {exc}"
    if completed.returncode == 0:
        return True, None
    if completed.returncode == 1:
        return False, None
    detail = completed.stderr.strip() or "git merge-base failed"
    return False, f"could not compare benchmark commit ancestry: {detail}"


def _changed_benchmark_files(root: Path, recorded: str, current: str) -> list[str]:
    try:
        completed = subprocess.run(
            ["git", "diff", "--name-only", f"{recorded}..{current}"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        # An ancestry check already passed.  If a diff cannot be inspected,
        # fail closed by reporting an unknown benchmark file.
        return ["<unable to inspect git diff>"]
    paths = [line.strip().replace("\\", "/") for line in completed.stdout.splitlines()]
    return sorted(path for path in paths if _is_benchmark_affecting(path))


def _dirty_benchmark_files(root: Path) -> list[str]:
    """Return tracked or untracked benchmark-affecting paths in the worktree."""

    try:
        completed = subprocess.run(
            ["git", "status", "--porcelain=v1", "--untracked-files=all"],
            cwd=root,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return ["<unable to inspect worktree status>"]
    paths: set[str] = set()
    for line in completed.stdout.splitlines():
        if len(line) < 4:
            continue
        path = line[3:].strip().replace("\\", "/")
        # Rename entries are reported as "old -> new"; both sides can affect
        # benchmark behavior and must be treated as dirty.
        candidates = [part.strip() for part in path.split(" -> ")]
        paths.update(candidate for candidate in candidates if _is_benchmark_affecting(candidate))
    return sorted(paths)


def _is_benchmark_affecting(path: str) -> bool:
    return path in BENCHMARK_AFFECTING_FILES or path.startswith(BENCHMARK_AFFECTING_PREFIXES)


def _display_path(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root))
    except ValueError:
        return str(path.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
